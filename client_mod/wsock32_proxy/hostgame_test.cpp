static int g_fail = 0;
static void Check(bool ok, const char* what) {
    std::printf("%s  %s\n", ok ? "OK  " : "FAIL", what);
    if (!ok) ++g_fail;
}

// 뺄 칸을 빼고 다른 바이트 수 — 견준 바이트 수도 같이 돌려준다(0 이 「없었다」인지 「안 봤다」인지 가르려고)
static int Diff(const unsigned char* real, const unsigned char* mine, size_t n, const int* skip, size_t nskip, int& compared) {
    int bad = 0;
    compared = 0;
    for (size_t i = 0; i < n; ++i) {
        bool s = false;
        for (size_t k = 0; k < nskip; ++k) s = s || (int)i == skip[k];
        if (s) continue;
        ++compared;
        if (real[i] != mine[i]) {
            ++bad;
            std::printf("  +%zu 실물 0x%02x 지음 0x%02x\n", i, real[i], mine[i]);
        }
    }
    return bad;
}

int main() {
    // 실물 seed 방 = 로비 이름 seed · 방 사람 0 · 채널 사람 2(방장 자리 1 + seed) · 게임 서버 127.0.0.1
    const nox::wol::Raw raw = nox::wol::Marshal(hostgame::MyRoomInfo("seed"));
    unsigned char e[hostgame::kEntrySize], c[hostgame::kChannelSize];
    hostgame::BuildEntry(e, 0x11223344u, 0x55667788u, "127.0.0.1", raw);
    hostgame::BuildChannel(c, "seed's_game", 2, 0x7F000001u, raw);

    const int skipE[] = { 0, 1, 2, 3, 4, 5, 6, 7, 32, 33, 34, 35, 22, 23, 24, 25, 26, 27 };
    const int skipC[] = { 48, 49, 50, 51 };
    int nE = 0, nC = 0;
    const int badE = Diff(kRealEntry, e, sizeof(e), skipE, sizeof(skipE) / sizeof(skipE[0]), nE);
    const int badC = Diff(kRealChannel, c, sizeof(c), skipC, sizeof(skipC) / sizeof(skipC[0]), nC);
    char m[160];
    std::snprintf(m, sizeof(m), "① 항목 = 실물 (견줌 %d바이트 · 다름 %d)", nE, badE);
    Check(nE == 151 && badE == 0, m);
    std::snprintf(m, sizeof(m), "② 채널 = 실물 (견줌 %d바이트 · 다름 %d)", nC, badC);
    Check(nC == 264 && badC == 0, m);

    uint32_t self = 0, chan = 0;
    std::memcpy(&self, e + 0, 4);
    std::memcpy(&chan, e + 32, 4);
    Check((raw[9] | (raw[10] << 8)) == hostgame::kGamePort && raw[9] == 0x9e && raw[10] == 0x48 && self == 0x11223344u && chan == 0x55667788u,
          "③ 날것 포트 칸 = 18590(0x489e) · 항목 +0 = 넘긴 자기 주소 · +32 = 넘긴 채널 주소");
    std::printf("%s  fail=%d\n", g_fail ? "HOSTGAME FAIL" : "HOSTGAME PASS", g_fail);
    return g_fail ? 1 : 0;
}
